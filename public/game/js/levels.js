// ============================================================
// ГЕНЕРАТОР УРОВНЕЙ (детерминированный, по seed главы)
// ============================================================
function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Один сгенерированный уровень главы ch (0..19)
function genLevelDef(ch, idx, id) {
  const M = CHAPTER_META[ch];
  const isBossMid = idx === 9, isBossFin = idx === 19;
  const rng = mulberry32(ch * 7919 + idx * 104729 + 5);
  const d = idx;
  const R = (a, b) => a + Math.floor(rng() * (b - a + 1));

  const def = {
    id, name: M.names[idx], type: 'map', bg: M.bg(idx), chapter: ch,
    ground: [], plats: [], bricks: [], spikes: [], springs: [], saws: [],
    crumble: [], liquids: [],
    bottles: { runs: [], singles: [] }, hearts: [], plushes: [], enemies: [],
    spawn: { c: 2 }, factory: { c: 0 },
  };

  // ---------- БОССОВЫЕ АРЕНЫ (10-й и 20-й уровень главы) ----------
  if (isBossMid || isBossFin) {
    const w = 90;
    def.width = w;
    def.ground = [[0, w - 1]];
    def.plats = [[24, 8, 3], [42, 8, 3], [56, 8, 4]];
    def.spikes = [[18, 19], [64, 65]];
    def.bottles.runs = [[8, 10, 10], [36, 38, 10], [50, 52, 10], [70, 72, 10], [24, 26, 7], [42, 44, 7]];
    def.hearts = [[25, 7], [57, 7]];
    def.plushes = [[20, 10], [40, 10], [55, 10], [62, 10]];
    def.enemies = [['e', 14], ['e', 30], ['t', 48], ['e', 60]];
    if (ch >= 2) def.enemies.push(['j', 34]);
    if (ch === 2 && isBossFin) def.enemies.push(['a', 50]);
    if (ch === 3) { def.enemies.push(['f', 36, 5], ['a', 46]); }
    def.boss = { col: 76, hp: isBossFin ? M.bossHp.fin : M.bossHp.mid };
    def.factoryLocked = true;
    def.factory = { c: w - 5 };
    def.hints = [{ c: 30, text: 'Плюшки! Подбирай — кидай по вождю (X)' }];
    def.dialogue = { intro: isBossFin ? M.finIntro : M.midBossIntro, outro: isBossFin ? M.finOutro : M.midBossOutro };
    if (isBossFin) {
      if (ch === 3) {
        def.bg = 'bg_final';
        def.name = M.names[19];
        def.boss.hp = 12;
        def.bossOutro = DIALOGUES.happyAfterBoss;
        def.dialogue.outro = DIALOGUES.happyOutro;
        def.hints = [{ c: 30, text: 'ШЕФ ВСЕХ БУРМАЛДЕНОВ! Плюшки (X) + прыжки сверху!' }];
      }
      def.plats.push([68, 6, 3]);
    }
    // тайник под ареной: колодец-выход с батутом, вход через обманки-плиты
    def.under = [{ c0: 32, c1: 39, well: [32, 33], decoys: [36, 37], heart: true, plush: true }];
    return def;
  }

  // ---------- ОБЫЧНЫЕ УРОВНИ ----------
  const w = Math.min(170, 92 + d * 3 + R(0, 9));
  def.width = w;
  def.factory = { c: w - 4 };
  const busy = new Set();          // занятые колонки ряда 10 (препятствия)
  const mark = (c0, c1) => { for (let c = c0; c <= c1; c++) busy.add(c); };

  // земля: стартовая площадка → сегменты с ямами → финальная площадка
  const pitMax = M.pit + Math.min(2, Math.floor(d / 5));
  const startPad = R(6, 8);
  def.ground.push([0, startPad]);
  let c = startPad + 1;
  const pits = [], segs = [];
  while (true) {
    if (w - c < 22) break;                       // остаток целиком станет финальной площадкой
    let pitW = (c > startPad + 5 && rng() < 0.6) ? R(2, pitMax) : 0;
    if (pitW && c + pitW > w - 14) pitW = 0;
    if (pitW) { pits.push([c, c + pitW - 1, pitW]); c += pitW; }
    const seg = R(5, 12);
    def.ground.push([c, c + seg - 1]);
    segs.push([c, c + seg - 1]);
    c += seg;
    if (w - c < 8) {                             // добиваем хвост землёй до края
      def.ground[def.ground.length - 1][1] = w - 1;
      segs[segs.length - 1][1] = w - 1;
      c = w;
      break;
    }
  }
  if (c < w) { def.ground.push([c, w - 1]); segs.push([c, w - 1]); }

  // сегменты для препятствий/врагов: не трогаем зону завода и старт
  const placeSegs = segs.filter(g => g[1] < w - 10 && g[0] > 8);

  // жидкость в ямах
  pits.forEach(([p0, p1]) => def.liquids.push([p0, p1]));

  // сыпучие мосты через широкие ямы (со 2-й половины главы)
  pits.forEach(([p0, p1, pw]) => {
    if (pw >= 4 && d >= 4 && rng() < 0.6) { def.crumble.push([p0, 10, pw]); mark(p0, p1); }
  });

  // секретка под землёй — ПЕРЕД препятствиями: комната первой занимает
  // колонки (mark), шипы/пилы/батуты/враги поверх входа не встанут
  planUnder(def, segs, busy, mark, R, ch, rng);

  // батуты: у широких ям + случайные
  const springCount = ch === 1 ? (idx >= 3 ? R(1, 2) : 0) : (ch === 2 ? (idx >= 2 ? R(1, 3) : 0) : R(2, 3));
  let placed = 0;
  pits.forEach(([p0, p1, pw]) => {
    if (pw >= 4 && placed < springCount && !busy.has(p0 - 1)) {
      def.springs.push([p0 - 1]); mark(p0 - 1, p0 - 1); placed++;
    }
  });
  for (let i = placed; i < springCount && placeSegs.length; i++) {
    const g = placeSegs[R(0, placeSegs.length - 1)];
    const sc = R(g[0] + 1, Math.max(g[0] + 1, g[1] - 1));
    if (!busy.has(sc)) { def.springs.push([sc]); mark(sc, sc); }
  }

  // пилы в земле
  const sawCount = ch === 1 ? (d >= 6 ? R(0, 2) : 0) : ch === 2 ? (d >= 3 ? R(1, 3) : 0) : R(1, 4);
  for (let i = 0; i < sawCount && placeSegs.length; i++) {
    const g = placeSegs[R(0, placeSegs.length - 1)];
    const sc = R(g[0] + 1, Math.max(g[0] + 1, g[1] - 1));
    if (!busy.has(sc) && !busy.has(sc - 1) && !busy.has(sc + 1)) { def.saws.push([sc]); mark(sc - 1, sc + 1); }
  }

  // шипы
  const spikeCount = Math.min(6, Math.floor(d / 3) + (rng() < 0.5 ? 1 : 0));
  for (let i = 0; i < spikeCount && placeSegs.length; i++) {
    const g = placeSegs[R(0, placeSegs.length - 1)];
    const sc = R(g[0] + 1, Math.max(g[0] + 1, g[1] - 2));
    if (!busy.has(sc) && !busy.has(sc + 1)) {
      const wide = (d >= 6 && rng() < 0.4) ? 2 : 1;
      def.spikes.push([sc, sc + wide - 1]); mark(sc, sc + wide);
    }
  }

  // платформы (ряд 8 в основном, ряд 6 — только рядом с рядом 8)
  const platCount = 3 + Math.floor(d / 3) + R(0, 2);
  const row8Plats = [];
  for (let i = 0; i < platCount && segs.length; i++) {
    const g = segs[R(0, segs.length - 1)];
    const pc = R(g[0], Math.max(g[0], g[1] - 4));
    const len = R(3, 5);
    let pr = 8;
    if (rng() < 0.3 && row8Plats.some(([pc8]) => Math.abs(pc8 - pc) <= 5)) pr = 6;
    def.plats.push([pc, pr, len]);
    if (pr === 8) row8Plats.push([pc, len]);
  }

  // враги
  const pool = ['e', 'e'];
  if (d >= 2 || ch >= 2) pool.push('t');
  if ((ch === 1 && d >= 5) || (ch === 2 && d >= 2) || ch === 3) pool.push('j', 'e');
  if ((ch === 1 && d >= 8) || (ch === 2 && d >= 5) || (ch === 3 && d >= 2)) pool.push('f');
  if ((ch === 2 && d >= 8) || (ch === 3 && d >= 6)) pool.push('a');
  const eCount = Math.min(13, 3 + Math.floor(d * 0.55));
  let hasArmored = false;
  for (let i = 0; i < eCount; i++) {
    const type = pool[R(0, pool.length - 1)];
    if (type === 'f') {
      def.enemies.push(['f', R(12, w - 14), R(4, 6)]);
      continue;
    }
    if (type === 'a') hasArmored = true;
    if (rng() < 0.25 && def.plats.length) {
      const [pc, pr, len] = def.plats[R(0, def.plats.length - 1)];
      def.enemies.push([type, pc + R(0, len - 1), pr - 1]);
    } else if (placeSegs.length) {
      const g = placeSegs[R(0, placeSegs.length - 1)];
      const ec = R(Math.max(g[0], 10), Math.max(g[0] + 1, g[1] - 1));
      if (!busy.has(ec)) { def.enemies.push([type, ec]); mark(ec, ec); }
    }
  }
  // плюшки/сердечки «на земле» — только на свободной колонке (не в шипах/пилах)
  const freeCol = (a, b) => {
    for (let t = 0; t < 14; t++) { const c = R(a, b); if (!busy.has(c)) return c; }
    return -1;
  };
  if (hasArmored) {
    const q1 = freeCol(12, Math.max(13, w - 20));
    if (q1 >= 0) def.plushes.push([q1, 10]);
    const q2 = freeCol(12, Math.max(13, w - 20));
    if (q2 >= 0 && q2 !== q1) def.plushes.push([q2, 10]);
  }

  // чекушки: ряды на земле, на платформах, дуги над ямами.
  // Занятые колонки (шипы/пилы/батуты/обманки) пропускаем — чекушка
  // никогда не лежит в опасности
  segs.forEach(([g0, g1], si) => {
    if (si === 0 || rng() < 0.85) {
      const b0 = Math.min(g0 + 1, g1 - 2), b1 = b0 + R(0, 2);
      for (let c = b0; c <= b1; c++) if (!busy.has(c)) def.bottles.runs.push([c, c, 10]);
    }
  });
  def.plats.forEach(([pc, pr, len]) => {
    if (rng() < 0.7) def.bottles.singles.push([pc + Math.floor(len / 2), pr - 1]);
  });
  pits.forEach(([p0, p1]) => {
    def.bottles.singles.push([p0, 8]);
    if (p1 > p0) def.bottles.singles.push([p1, 8]);
  });

  // сердечки
  const hCount = R(1, 2);
  for (let i = 0; i < hCount; i++) {
    if (def.plats.length) {
      const [pc, pr, len] = def.plats[R(0, def.plats.length - 1)];
      def.hearts.push([pc + Math.floor(len / 2), pr - 1]);
    } else {
      const hc = freeCol(20, Math.max(21, w - 20));
      if (hc >= 0) def.hearts.push([hc, 10]);
    }
  }

  // подсказки и диалоги
  def.hints = (M.hints || []).filter(([hIdx]) => hIdx === idx).map(([, text]) => ({ c: 6, text }));
  if (idx === 0) {
    def.dialogue = { intro: M.intro, outro: M.outro0 || null };
  } else {
    const pair = M.pool[idx % M.pool.length];
    def.dialogue = { intro: pair, outro: null };
  }
  return def;
}

// ============================================================
// СЕКРЕТНЫЕ КОМНАТЫ ПОД ЗЕМЛЁЙ (генератор)
// Длинный сегмент земли → под ним комната с лутом: вход — 2 тайла-
// обманки 'D' (выглядят как земля, проваливаешься), выход — колодец
// из 2 колонок с батутом на дне (выбрасывает наружу). Поверхность
// над входом/колодцем чистится (mark): шипы/пилы/враги туда не встанут.
// ============================================================
function planUnder(def, segs, busy, mark, R, ch, rng) {
  def.under = def.under || [];
  const w = def.width;
  // прогоны сплошной земли (ряды 11-12): под ямами комнату не рыть —
  // жижа ямы оказалась бы потолком комнаты
  const solid = new Array(w).fill(false);
  (def.ground || []).forEach(([a, b]) => { for (let c = a; c <= b; c++) if (c >= 0 && c < w) solid[c] = true; });
  const runs = [];
  let s = -1;
  for (let c = 0; c <= w; c++) {
    if (c < w && solid[c]) { if (s < 0) s = c; }
    else if (s >= 0) { if (c - s >= 9 && s > 8 && c <= w - 8) runs.push([s, c - 1]); s = -1; }
  }
  if (!runs.length) return;
  const build = (first) => {
    const [a, b] = runs[R(0, runs.length - 1)];
    const rw = R(6, Math.min(9, b - a - 3));  // ширина комнаты (6-9, влезает в прогон)
    const c0 = R(a + 1, b - rw);
    const c1 = c0 + rw - 1;
    const well = [c0, c0 + 1];                // колодец-выход у левого края
    const d0 = c0 + 3 + R(0, rw - 6);         // обманки-вход правее колодца
    for (let c = well[0] - 1; c <= well[1] + 1; c++) if (busy.has(c)) return false;
    for (let c = d0 - 1; c <= d0 + 2; c++) if (busy.has(c)) return false;
    def.under.push({
      c0, c1, well, decoys: [d0, d0 + 1],
      heart: first ? true : rng() < 0.5,
      plush: ch >= 2,
    });
    mark(well[0] - 1, well[1] + 2);
    mark(d0 - 1, d0 + 2);
    return true;
  };
  build(true);
  // вторая комната на длинных картах — не внахлёст с первой
  if (w >= 135 && rng() < 0.8 && def.under.length) {
    const before = def.under.length;
    if (build(false) && def.under.length > before) {
      const u = def.under[def.under.length - 1], f = def.under[0];
      if (f !== u && !(u.c1 < f.c0 - 4 || u.c0 > f.c1 + 4)) def.under.pop();
    }
  }
}

function genChapter(ch) {
  const list = [];
  for (let i = 0; i < 20; i++) list.push(genLevelDef(ch, i, 6 + (ch - 1) * 20 + i));
  return list;
}

