// ============================================================
// Уровни и сюжет
// Легенда тайлов: '#' земля, 'B' кирпич, '=' платформа (можно спрыгнуть),
// 'C' сыпучая платформа (обрушается), '^' шипы, 'L' жидкость (полынья/лава/кислота),
// 'v' батут, 'S' пила, 'c' чекушка, 'H' сердечко, 'e' бурмалденец, 't' метатель,
// 'f' летун, 'j' прыгун, 'a' щитоносец, 'G' вождь-босс, 'F' завод (выход), 'P' старт
// ============================================================
const ROWS = 18;          // высота карты: 0-12 поверхность, 13-17 подземелье (секретные комнаты)
const TILE = 40;          // размер тайла
const SURFACE_ROWS = 13;  // «старая» высота мира (поверхность) — низ земли, ниже только подземка

function buildLevel(def) {
  const w = def.width;
  const grid = Array.from({ length: ROWS }, () => Array(w).fill('.'));
  const spawns = { enemies: [], bottles: [], hearts: [], tomahawks: [], plushes: [], custom: [] };

  // земля: поверхность (2 ряда) + сплошное подземелье ниже — снизу никогда не видно фон
  (def.ground || []).forEach(([c0, c1]) => {
    for (let r = 11; r <= 12; r++) for (let c = c0; c <= c1; c++) grid[r][c] = '#';
  });
  for (let r = 13; r < ROWS; r++) grid[r].fill('#');

  // секретные комнаты под землёй: def.under = [{ c0, c1, well, decoys, heart, plush }]
  // комната — воздух ряды 13-16 (пол — ряд 17); колодец — 2 колонки без земли
  // (ряды 11-12) с батутом на дне = выход наружу; обманки 'D' — выглядят как
  // земля, но проваливаешься внутрь (враги их обходят — считают краем)
  (def.under || []).forEach((u) => {
    if (!u || typeof u !== 'object') return; // битая секретка из панели — пропустить, не падать
    for (let r = 13; r <= 16; r++) for (let c = u.c0; c <= u.c1; c++) if (c >= 0 && c < w) grid[r][c] = '.';
    (u.well || []).forEach((c) => { for (let r = 11; r <= 12; r++) if (c >= 0 && c < w) grid[r][c] = '.'; });
    // батут в КАЖДОЙ колонке колодца: упал в колодец — сразу выбросило наружу
    // (колодец = выход; вход в комнату — только через обманки)
    (u.well || []).forEach((c) => { if (c >= 0 && c < w) grid[16][c] = 'v'; });
    (u.decoys || []).forEach((c) => {
      for (let r = 11; r <= 12; r++) if (c >= 0 && c < w && grid[r][c] === '#') grid[r][c] = 'D';
    });
  });
  // кирпичи: прямоугольники [c0, r0, c1, r1]
  (def.bricks || []).forEach(([c0, r0, c1, r1]) => {
    for (let r = r0; r <= r1; r++) for (let c = c0; c <= c1; c++) grid[r][c] = 'B';
  });
  // платформы [c, r, len]
  (def.plats || []).forEach(([c, r, len]) => {
    for (let i = 0; i < len; i++) if (r >= 0 && r < ROWS && c + i < w) grid[r][c + i] = '=';
  });
  // сыпучие платформы [c, r, len] — обрушаются, когда на них постояли
  (def.crumble || []).forEach(([c, r, len]) => {
    for (let i = 0; i < len; i++) if (r >= 0 && r < ROWS && c + i < w) grid[r][c + i] = 'C';
  });
  // шипы [c0, c1] — на земле (ряд 10), либо [c0, c1, ряд] — например на платформе
  (def.spikes || []).forEach(([c0, c1, r]) => {
    const row = (r === undefined || r === null) ? 10 : r;
    if (row >= 0 && row < ROWS) for (let c = c0; c <= c1; c++) grid[row][c] = '^';
  });
  // жидкость [c0, c1] — дно ям (ряд 12), либо [c0, c1, ряд]
  (def.liquids || []).forEach(([c0, c1, r]) => {
    const row = (r === undefined || r === null) ? 12 : r;
    if (row >= 0 && row < ROWS) for (let c = c0; c <= c1; c++) grid[row][c] = 'L';
  });
  // батуты [c] — на земле (ряд 10), либо [c, ряд]
  (def.springs || []).forEach(([c, r]) => {
    const row = (r === undefined || r === null) ? 10 : r;
    if (row >= 0 && row < ROWS) grid[row][c] = 'v';
  });
  // пилы [c] — в земле (ряд 10), либо [c, ряд]
  (def.saws || []).forEach(([c, r]) => {
    const row = (r === undefined || r === null) ? 10 : r;
    if (row >= 0 && row < ROWS) grid[row][c] = 'S';
  });
  // чекушка
  (def.bottles?.runs || []).forEach(([c0, c1, r]) => {
    for (let c = c0; c <= c1; c++) spawns.bottles.push({ c, r });
  });
  (def.bottles?.singles || []).forEach(([c, r]) => spawns.bottles.push({ c, r }));
  // сердечки
  (def.hearts || []).forEach(([c, r]) => spawns.hearts.push({ c, r }));
  // плюшки (боеприпас для стрельбы по боссу и щитоносцам)
  (def.plushes || []).forEach(([c, r]) => spawns.plushes.push({ c, r }));
  // лут внутри секретных комнат: чекушки по полу, сердечко в центре (берётся
  // в прыжке), плюшка-патроны в главах 2-3
  (def.under || []).forEach((u) => {
    if (!u || typeof u !== 'object') return; // битая секретка из панели — пропустить, не падать
    for (let c = u.c0 + 1; c <= u.c1; c++) {
      if (c >= 0 && c < w && grid[16][c] !== 'v') spawns.bottles.push({ c, r: 16 });
    }
    if (u.heart) spawns.hearts.push({ c: Math.floor((u.c0 + u.c1) / 2), r: 14 });
    if (u.plush) spawns.plushes.push({ c: u.c0 + 1, r: 15 });
  });
  // враги: [тип, колонка] — спавн на землю (ряд 10), либо [тип, колонка, ряд] — на платформу
  (def.enemies || []).forEach(([type, c, r]) => spawns.enemies.push({ type, c, r: (r === undefined) ? 10 : r }));
  if (def.boss) spawns.enemies.push({ type: 'boss', c: def.boss.col, r: 9, hp: def.boss.hp });
  // кастомные объекты из админ-панели: { 'obj-id': [[c,r],...] }
  if (def.custom && typeof def.custom === 'object') {
    Object.entries(def.custom).forEach(([type, list]) => {
      (list || []).forEach(([c, r]) => spawns.custom.push({ type, c, r }));
    });
  }

  return {
    def, w, grid, spawns,
    crumble: new Map(),          // состояние сыпучих платформ 'c,r' -> {t, broken}
    spawnC: def.spawn?.c ?? 2,
    factoryC: def.factory?.c ?? w - 6,
    hints: def.hints || [],
  };
}

